SELECT YEAR(NOW()) FROM DUAL;
SELECT MONTH(NOW()) FROM DUAL;
SELECT DATE(NOW()) FROM DUAL;

SELECT TIME(NOW()) FROM DUAL;
SELECT HOUR(NOW()) FROM DUAL;
