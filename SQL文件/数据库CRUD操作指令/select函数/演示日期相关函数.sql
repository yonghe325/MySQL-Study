# FROM_UNIXTIME() 可以把一个unix_timestamp秒数转换为一个指定格式的日期,用百分号作为占位符
## 在开发中可以存放一个整数表示一个时间,运用此函数转换为日期
SELECT FROM_UNIXTIME(UNIX_TIMESTAMP(),'%Y-%M-%d %H:%I:%s') FROM DUAL;
# unix_timestamp  返回1970-1-1到现在的秒数,即真正的==时间戳==
SELECT UNIX_TIMESTAMP() FROM DUAL;
SELECT UNIX_TIMESTAMP()/(24*3600*365) FROM DUAL;